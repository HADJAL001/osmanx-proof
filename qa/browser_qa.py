"""Optional browser acceptance suite: pip install playwright; playwright install chromium."""
import asyncio, json, time, pathlib, os
from playwright.async_api import async_playwright

BASE=os.environ.get('PROOF_BASE','http://127.0.0.1:3100')
OUT=pathlib.Path(__file__).parent

async def main():
    results={"checks": [], "console_errors": [], "screenshots": []}
    async with async_playwright() as p:
        browser=await p.chromium.launch(headless=True, executable_path='/usr/bin/chromium', args=['--no-sandbox'])
        ctx=await browser.new_context(viewport={"width":1440,"height":900}, device_scale_factor=1)
        page=await ctx.new_page()
        page.on('pageerror', lambda e: results['console_errors'].append(str(e)))
        page.on('console', lambda m: results['console_errors'].append(m.text) if m.type=='error' else None)
        async def check(name, locator):
            await page.locator(locator).first.wait_for(timeout=10000)
            results['checks'].append(name)
        async def shot(name):
            await page.screenshot(path=str(OUT/name),full_page=True)
            results['screenshots'].append(name)
        await page.goto(BASE+'/',wait_until='networkidle')
        await check('auth page','form#authForm')
        await shot('01_auth_desktop.png')
        stamp=int(time.time()*1000)
        await page.locator('#authForm [name=name]').fill('Demo Specialist')
        await page.locator('#authForm [name=email]').fill(f'demo_{stamp}@example.org')
        await page.locator('#authForm [name=password]').fill('VeryStrongPassword2026!')
        await page.locator('#authForm button[type=submit]').click()
        await check('signup and overview','.hero')
        await shot('02_dashboard_desktop.png')
        await page.locator('.hero [data-action=newquote]').click()
        await check('quote composer','#quoteForm')
        await page.locator('#quoteForm [name=title]').fill('Corporate website redesign')
        await page.locator('#quoteForm [name=clientName]').fill('Atlas Studio')
        await page.locator('#quoteForm [name=desc]').fill('Design and responsive development')
        await page.locator('#quoteForm [name=qty]').fill('1')
        await page.locator('#quoteForm [name=price]').fill('70000')
        await page.locator('#quoteForm [name=cost]').fill('25000')
        await page.locator('#quoteForm [name=discount]').fill('5000')
        await page.locator('#quoteForm [name=tax]').fill('0')
        assert '65' in await page.locator('#prevTotal').inner_text(), 'wrong quote calculation'
        results['checks'].append('quote calculation preview')
        await shot('03_quote_composer_desktop.png')
        await page.locator('#quoteForm button[type=submit]').click()
        await check('saved quote visible','.table [data-action=viewquote]')
        await page.locator('.table [data-action=viewquote]').first.click()
        await check('quote detail rendered','.detail-grid')
        await shot('04_quote_detail_desktop.png')
        await page.locator('.sidebar [data-section=billing]').click()
        await check('billing screen','.plan-card')
        await page.locator('[data-action=invoice]').click()
        await check('invoice issued','[data-action=sandboxpay]')
        page.once('dialog',lambda dialog: asyncio.create_task(dialog.accept()))
        await page.locator('[data-action=sandboxpay]').click()
        await check('sandbox payment complete','.status.paid')
        await shot('05_billing_sandbox_desktop.png')
        await page.locator('.sidebar [data-section=referrals]').click()
        await check('referral code and transparent terms','.ref-code')
        await shot('06_referrals_desktop.png')
        await page.locator('.sidebar [data-section=support]').click()
        await check('support form','#disputeForm')
        await page.locator('#disputeForm [name=subject]').fill('Need a copy of invoice')
        await page.locator('#disputeForm [name=detail]').fill('I need an additional invoice copy for my records.')
        await page.locator('#disputeForm button[type=submit]').click()
        await check('support ticket added','.callout')
        await shot('07_support_desktop.png')
        await page.set_viewport_size({"width":390,"height":844})
        await page.goto(BASE+'/',wait_until='networkidle')
        await check('mobile layout','.mobile-nav')
        await shot('08_dashboard_mobile.png')
        await page.locator('.mobile-nav [data-section=quotes]').click()
        await check('mobile quotes view','.page-title')
        await shot('09_quotes_mobile.png')
        results['checks'].append('mobile navigation')
        await browser.close()
    (OUT/'results.json').write_text(json.dumps(results,ensure_ascii=False,indent=2),encoding='utf8')
    print(json.dumps(results,ensure_ascii=False,indent=2))
    if results['console_errors']:
        raise SystemExit('Browser console errors detected')

if __name__=='__main__': asyncio.run(main())
