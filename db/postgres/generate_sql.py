from pathlib import Path
src=Path(__file__).resolve().parents[1]/'schema.sql'
out=Path(__file__).resolve().parent/'001_schema.sql'
s=src.read_text()
lines=[]
for line in s.splitlines():
 if line.strip().startswith('PRAGMA '):continue
 lines.append(line)
s='\n'.join(lines)
s=s.replace('INTEGER PRIMARY KEY AUTOINCREMENT','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
out.write_text('-- Generated from db/schema.sql for a faithful SQLite R1-R3 data cutover.\n-- Values preserved as TEXT for ISO dates, BIGINT/INTEGER for cents; test against PostgreSQL before use.\n'+s+'\n')
print('written',out)
